import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const graph = JSON.parse(await readFile(new URL('../website/dist/graph.json', import.meta.url), 'utf8'));
const url = process.env.ATLAS_URL || new URL('../website/dist/index.html', import.meta.url).href;
const browser = await chromium.launch({headless: true, executablePath: process.env.CHROMIUM_EXECUTABLE || undefined});
try {
  const page = await browser.newPage({viewport: {width: 1440, height: 960}});
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(url);
  await page.locator('.graph-node').first().waitFor();
  assert.equal(await page.locator('#definition-count').textContent(), String(graph.nodes.filter(n => n.category === 'definition').length));
  await page.locator('#all-view').click();
  assert.equal(await page.locator('.graph-node').count(), graph.nodes.length);
  assert.equal(await page.locator('.edge').count(), graph.edges.length);
  await page.locator('[data-kind="statement"]').click();
  assert.equal(await page.locator('.graph-node.definition').count(), 0);
  assert.equal(await page.locator('.graph-node').count(), graph.nodes.filter(n => n.category === 'statement').length);
  await page.locator('[data-kind="all"]').click();
  await page.locator('#module-filter').selectOption('Random');
  assert.equal(await page.locator('.graph-node').count(), graph.nodes.filter(n => n.module === 'Random').length);
  await page.locator('#search').fill('conditional_fresh_cell');
  assert.equal(await page.locator('.declaration-item').count(), 1);
  await page.locator('.declaration-item').click();
  assert.equal(await page.locator('#inspector h2').textContent(), 'conditional_fresh_cell');
  await page.locator('#focus-selected').click();
  const chosen = graph.nodes.find(n => n.id === 'WordRam.conditional_fresh_cell');
  assert.equal(await page.locator('.graph-node').count(), new Set([chosen.id, ...chosen.dependencies, ...chosen.dependents]).size);
  await page.locator('#search').fill('no_such_declaration_123');
  assert.equal(await page.locator('.declaration-item').count(), 0);
  assert.match(await page.locator('.empty-list').textContent(), /No matching/);
  await page.locator('#search').fill('');
  const before = await page.locator('#zoom-level').textContent();
  await page.locator('#zoom-in').click();
  assert.notEqual(await page.locator('#zoom-level').textContent(), before);
  await page.locator('#fit').click();
  const transform = await page.locator('#viewport').getAttribute('transform');
  const box = await page.locator('#graph').boundingBox();
  await page.mouse.move(box.x + 25, box.y + 70);
  await page.mouse.down();
  await page.mouse.move(box.x + 90, box.y + 130, {steps: 5});
  await page.mouse.up();
  assert.notEqual(await page.locator('#viewport').getAttribute('transform'), transform);
  await page.locator('#fit').click();
  const graphNode = page.locator('.graph-node').first();
  const id = await graphNode.getAttribute('data-id');
  await graphNode.focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('.qualified-name').textContent(), id);
  const deepLink = page.url();
  await page.reload();
  assert.equal(await page.locator('.qualified-name').textContent(), id);
  assert.equal(page.url(), deepLink);
  const sourceURL = await page.locator('#inspector .source-link').getAttribute('href');
  const source = await browser.newPage();
  await source.goto(new URL(sourceURL, page.url()).href);
  const target = source.locator(':target');
  assert.equal(await target.count(), 1);
  assert.match(await target.textContent(), /def|theorem|abbrev|inductive|structure|instance/);
  await source.close();
  await page.locator('#about-button').click();
  assert.equal(await page.locator('#about').evaluate(el => el.open), true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#about').evaluate(el => el.open), false);
  await page.setViewportSize({width: 390, height: 844});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile layout overflows horizontally');
  await page.locator('#reset').click();
  assert.equal(await page.locator('#inspector h2').textContent(), 'run_resume');
  assert.deepEqual(errors, []);
  console.log(`Browser checks passed (${url.startsWith('file:') ? 'offline file' : 'HTTP'}): complete graph, filters, search, selection, keyboard, pan/zoom, deep links, source anchors, dialog, mobile layout.`);
} finally {
  await browser.close();
}
